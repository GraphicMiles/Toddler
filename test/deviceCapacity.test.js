import assert from 'node:assert/strict';
import { assessModelCompatibility, estimateModelRamBytes, getModelSizeBytes, formatModelSize, ramGigabytesForCompatibility } from '../src/utils/deviceCapacity.js';
assert.equal(getModelSizeBytes({ size: 1, sizeUnit: 'GB' }), 1_000_000_000);
assert.equal(getModelSizeBytes({ size: 500, sizeUnit: 'MB', sizeBytes: 491_400_032 }), 491_400_032);
assert.equal(formatModelSize(1_000_000_000), '1 GB');
assert.equal(ramGigabytesForCompatibility(4 * 1024 ** 3), 4);
assert.equal(ramGigabytesForCompatibility(null, 6), 6);
const model = { sizeBytes: 500_000_000, minRamBytes: 2 * 1024 ** 3, profile: { contextTokens: 4096 } };
assert.ok(estimateModelRamBytes(model) >= 2 * 1024 ** 3);
assert.equal(assessModelCompatibility(model, { ramBytes: 4 * 1024 ** 3, availableRamBytes: 2 * 1024 ** 3, availableStorageBytes: 2_000_000_000 }).compatible, true);
console.log('device capacity tests passed');
